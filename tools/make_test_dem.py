#!/usr/bin/env python3
"""Generate the SYNTHETIC test terrain used by the automated tests and the demo.

This is NOT Martian data. It is an analytic surface with known geometry:
  * a gentle regional tilt,
  * a north-south ridge 150 m high with steep flanks (steeper than 60 degrees) and one 450 m wide pass,
  * a hill with moderate slopes and a steeper mound (about 15 degrees) on the direct line to the pass,
  * a no-data patch, stored with a sentinel and a z_scale to exercise the importer.
Cell size 25 m, 100 x 80 cells = 2.5 km x 2.0 km. Local coordinates only (no georeference).

Also writes a tiny PDS3-style fixture (label + raw float32) for testing the PDS reader:
    python3 tools/make_test_dem.py --pds-fixture test/fixtures
"""
import argparse, json, math, struct, pathlib

W, H, CELL = 100, 80, 25.0
NODATA = -32768
Z_SCALE = 0.1

def smooth(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3 - 2 * t)

def elevation(x, y):
    z = -0.02 * y                                   # regional tilt, about 1.1 degrees
    pass_factor = 1 - smooth((y - 1100) / 150) * (1 - smooth((y - 1700) / 150))   # pass open for y = 1250..1700 m
    z += 150.0 * smooth((x - 1220) / 60) * (1 - smooth((x - 1340) / 60)) * pass_factor   # ridge
    z += 45.0 * math.exp(-(((x - 600) / 280) ** 2 + ((y - 450) / 220) ** 2))   # hill, slopes ~ 10-14 degrees
    z += 45.0 * math.exp(-(((x - 770) / 110) ** 2 + ((y - 880) / 110) ** 2))   # mound on the direct line to the pass, ~15 degrees
    return z

def build():
    z = []
    for j in range(H):
        for i in range(W):
            x, y = (i + .5) * CELL, (j + .5) * CELL
            if 24 <= i < 30 and 38 <= j < 44:       # no-data patch
                z.append(NODATA)
            else:
                z.append(int(round(elevation(x, y) / Z_SCALE)))
    return z

def tile():
    return {
        "format": "mars-survival-tile", "version": 1,
        "name": "Synthetic test terrain (not Mars)", "kind": "synthetic-test",
        "width": W, "height": H, "cell_x_m": CELL, "cell_y_m": CELL,
        "elevation_unit": "m", "z_scale": Z_SCALE, "z_offset": 0, "nodata": NODATA,
        "z": build(),
        "source": {"product_id": None, "mission": None, "instrument": None, "url": None,
                   "credit": "Generated by tools/make_test_dem.py; contains no NASA data.",
                   "processing": ["Analytic surface, see script"]},
        "notes": ["Local metric coordinates only; no latitude/longitude.",
                  "Targets below are fictional and exist only to exercise the science route."],
        "default_route": {"start": {"x_m": 312.5, "y_m": 512.5}, "destination": {"x_m": 2262.5, "y_m": 512.5}},
        "targets": [
            {"name": "Test target A (hill flank)", "x_m": 600, "y_m": 900, "radius_m": 250, "note": "fictional"},
            {"name": "Test target B (near the pass)", "x_m": 1250, "y_m": 1480, "radius_m": 250, "note": "fictional"},
            {"name": "Test target C (east plain)", "x_m": 2000, "y_m": 1000, "radius_m": 250, "note": "fictional"}
        ]
    }

def pds_fixture(outdir):
    out = pathlib.Path(outdir); out.mkdir(parents=True, exist_ok=True)
    lines, samples, scale = 40, 60, 2.0
    vals = []
    for j in range(lines):
        for i in range(samples):
            v = 100 + 0.6 * j + 0.1 * i  # gentle tilt
            if 10 <= i < 14 and 10 <= j < 14:
                v = -3.4028226550889045e+38          # MISSING_CONSTANT
            vals.append(v)
    (out / "pds_fixture.IMG").write_bytes(struct.pack("<%df" % len(vals), *vals))
    label = f"""PDS_VERSION_ID = PDS3
RECORD_TYPE = FIXED_LENGTH
RECORD_BYTES = {samples * 4}
^IMAGE = "pds_fixture.IMG"
OBJECT = IMAGE_MAP_PROJECTION
  MAP_PROJECTION_TYPE = EQUIRECTANGULAR
  A_AXIS_RADIUS = 3396.19 <KM>
  CENTER_LATITUDE = 0.0 <DEG>
  CENTER_LONGITUDE = 77.0 <DEG>
  LINE_PROJECTION_OFFSET = 1100.0 <PIXEL>
  SAMPLE_PROJECTION_OFFSET = 500.0 <PIXEL>
  MAP_SCALE = {scale} <METERS/PIXEL>
END_OBJECT = IMAGE_MAP_PROJECTION
OBJECT = IMAGE
  LINES = {lines}
  LINE_SAMPLES = {samples}
  SAMPLE_TYPE = PC_REAL
  SAMPLE_BITS = 32
  MISSING_CONSTANT = 16#FF7FFFFB#
  SCALING_FACTOR = 1.0
  OFFSET = 0.0
END_OBJECT = IMAGE
END
"""
    (out / "pds_fixture.LBL").write_text(label)

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="public/data/test-terrain.json")
    ap.add_argument("--pds-fixture", metavar="DIR")
    a = ap.parse_args()
    if a.pds_fixture:
        pds_fixture(a.pds_fixture)
    else:
        p = pathlib.Path(a.out); p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(tile(), separators=(",", ":")))
        print("wrote", p, p.stat().st_size, "bytes")
